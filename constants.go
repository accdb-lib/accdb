package accdb

// Database format versions
type JetVersion uint8

const (
	JetVersion3 JetVersion = 0x00 // Access 97
	JetVersion4 JetVersion = 0x01 // Access 2000/2002/2003
	JetVersion5 JetVersion = 0x02 // Access 2007+ (.accdb)
)

// Page sizes for different versions
const (
	PageSizeJet3 = 2048
	PageSizeJet4 = 4096
	PageSizeJet5 = 4096
)

// Page types
type PageType byte

const (
	PageTypeDatabase     PageType = 0x00
	PageTypeData         PageType = 0x01
	PageTypeTableDef     PageType = 0x02
	PageTypeIntermediate PageType = 0x03
	PageTypeLeafIndex    PageType = 0x04
	PageTypePageUsage    PageType = 0x05
)

// Column types
type ColumnType byte

const (
	ColTypeBoolean  ColumnType = 0x01
	ColTypeByte     ColumnType = 0x02
	ColTypeInt      ColumnType = 0x03
	ColTypeLongInt  ColumnType = 0x04
	ColTypeMoney    ColumnType = 0x05
	ColTypeFloat    ColumnType = 0x06
	ColTypeDouble   ColumnType = 0x07
	ColTypeDateTime ColumnType = 0x08
	ColTypeBinary   ColumnType = 0x09
	ColTypeText     ColumnType = 0x0A
	ColTypeOLE      ColumnType = 0x0B
	ColTypeMemo     ColumnType = 0x0C
	ColTypeGUID     ColumnType = 0x0F
	ColTypeBigInt   ColumnType = 0x10
	ColTypeComplex  ColumnType = 0x12
)

// System table IDs
const (
	SysTableMSysObjects   = 2
	SysTableMSysAces      = 3
	SysTableMSysQueries   = 4
	SysTableMSysRelations = 5
)

// Object types in MSysObjects
type ObjectType byte

const (
	ObjTypeTable       ObjectType = 1
	ObjTypeQuery       ObjectType = 5
	ObjTypeLinkedTable ObjectType = 6
	ObjTypeSystemTable ObjectType = 0x80
)

// Database header offsets
const (
	OffsetJetVersion    = 0x14
	OffsetCodePage      = 0x3C
	OffsetEncryptionKey = 0x3E
	OffsetDbKey         = 0x42
	OffsetCollation     = 0x6E
	OffsetCreationDate  = 0x72
	HeaderMaskOffset    = 0x18
)

